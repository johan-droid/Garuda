"""Alembic must know about the saved-places table.

`SavedPlaceModel` is not imported by `app.models.entities`, so a migration
autogenerated from `Base.metadata` would silently omit the table. This test
reads the same thing Alembic reads - the live ORM metadata - and asserts the
table is there, so the omission is caught here rather than as a runtime
`no such table: saved_places`.
"""

from sqlalchemy import inspect

from app.db.session import Base, engine


def test_saved_places_is_registered_on_the_metadata() -> None:
    """The model must be imported somewhere the metadata can see it."""
    assert "saved_places" in Base.metadata.tables, (
        "SavedPlaceModel is not on Base.metadata. Nothing imports "
        "app.models.saved_place from a module the app or alembic/env.py "
        "loads, so create_all and autogenerate both skip the table."
    )


def test_saved_places_table_has_the_composite_primary_key() -> None:
    """(owner_id, place_id) is the idempotency key, so it must be the PK.

    A single-column primary key would let one visitor save the same place
    twice, which is exactly what the endpoint's idempotency promise forbids.
    """
    columns = {c.name: c for c in Base.metadata.tables["saved_places"].columns}
    assert set(columns) == {"owner_id", "place_id", "place_data", "created_at", "updated_at"}
    assert columns["owner_id"].primary_key is True
    assert columns["place_id"].primary_key is True
    assert columns["place_data"].nullable is False
